function stateTable=build_blanket_state_table(protocol,sampleRateHz,cameraFramePeriodS)
%BUILD_BLANKET_STATE_TABLE One programmed unit of blanket-mode states, in samples.
%   stateTable=BUILD_BLANKET_STATE_TABLE(protocol,rateHz,framePeriodS) turns
%   a resolved blanket-depolarization acquisition into the sample-exact
%   table that BOTH the DMD playlist and the DAQ waveforms are built from.
%   Every schedule is the same 0.2/0.8 ms cycle; they differ only in what
%   the second state of each cycle shows and at which level:
%
%     round_robin, target epoch:  blanket (union mask, mod488_v)
%                                 target  (target mask,  cell Vstim)
%     round_robin, gap:           blanket (union mask, mod488_v)
%                                 dark    (blank mask,   0 V)
%     recruitment_sweep:          blanket (blanket mask, this step's level)
%                                 dark    (blank mask,   0 V)
%     population_target_sweep:    as round_robin, with the union of every
%                                 selected cell's mask as the one target
%                                 and the sweep's level as its voltage
%
%   ONE TABLE, BOTH CHANNELS. Every state is one DMD picture and one DMD
%   trigger: the trigger's rising edge is the state's first sample, the same
%   sample on which mod488 takes the state's level (dmd_trigger_lead_samples
%   is 0). The only exception is deliberate and recorded per state:
%   mod488_guard_samples at the start of a target state stay at 0 V while the
%   DMD replaces the blanket mask, so Vstim never meets the full-FOV mask
%   during the trigger-to-display latency. Nothing else in the package
%   computes blanket timing; the playlist and both waveforms only read this.
%
%   ONE PROGRAMMED UNIT. The table holds one programmed unit - one round for
%   round_robin, the whole sweep for a calibration sweep - and the DAQ
%   repeats it round_count times from round_start_sample, so
%   expected_trigger_count = states_per_round x round_count, exactly. The
%   DMD playlist is shorter still when the mask sequence repeats inside the
%   unit; BUILD_BLANKET_DMD_SEQUENCE_PLAN finds that period.
%
%   SAMPLE CONVENTION. Sample s is DAQ sample s+1 in MATLAB terms and occurs
%   at s/rate. start_sample is relative to the unit's start, which is at
%   round_start_sample. Camera frame k is taken to start at sample
%   (k-1) x camera_frame_samples - the DAQ-triggered VU camera's first
%   trigger is high at the first DAQ sample.
%
%   Refuses, rather than rounds: a cycle, blanket phase, guard, unit start
%   or camera period that is not a whole number of samples; a cycle that is
%   not exactly one camera frame; a state too short for the DMD trigger
%   pulse plus one low sample; and logical events that are not exactly what
%   the frozen schedule says the DMD and mod488 will deliver.
%
%   See also BUILD_BLANKET_DMD_SEQUENCE_PLAN, BLANKET_DEPOLARIZATION_SPEC,
%   LUMINOS_ROUND_WAVEFORM.
arguments
    protocol (1,1) struct
    sampleRateHz double
    cameraFramePeriodS double
end
protocol=adaptive_optopatch.normalize_protocol(protocol);
blanket=adaptive_optopatch.blanket_depolarization_spec(protocol);
if ~blanket.enabled
    error("adaptive_optopatch:BlanketDepolarizationDisabled", ...
        "This acquisition does not enable blanket depolarization.");
end
if ~isscalar(sampleRateHz) || ~isfinite(sampleRateHz) || sampleRateHz<=0
    error("adaptive_optopatch:BlanketSampleRateRequired", ...
        "Blanket depolarization needs the live DAQ sample rate to build " + ...
        "its sample-exact state table.");
end
if ~isscalar(cameraFramePeriodS) || ~isfinite(cameraFramePeriodS) || ...
        cameraFramePeriodS<=0
    error("adaptive_optopatch:BlanketCameraPeriodRequired", ...
        "Blanket depolarization needs a DAQ-triggered voltage camera with " + ...
        "a known frame period: every modulation cycle starts on a frame.");
end
rate=double(sampleRateHz);
cycleSamples=exact_samples(blanket.cycle_period_s,rate,"cycle_period_s");
blanketSamples=exact_samples(blanket.blanket_fraction*blanket.cycle_period_s, ...
    rate,"blanket phase (blanket_fraction x cycle_period_s)");
targetSamples=cycleSamples-blanketSamples;
guardSamples=exact_samples(blanket.target_onset_guard_s,rate,"target_onset_guard_s");
frameSamples=exact_samples(cameraFramePeriodS,rate,"camera frame period");
if frameSamples~=cycleSamples
    error("adaptive_optopatch:BlanketCycleNotCameraFrame", ...
        "The %.6g ms modulation cycle must equal the %.6g ms camera frame " + ...
        "period, so that every cycle starts on a frame and every frame " + ...
        "integrates one identical cycle.", ...
        1000*cycleSamples/rate,1000*frameSamples/rate);
end
% Same pulse width the existing DMD trigger uses (max(3/rate, 20 us)), in
% whole samples, and the line has to fall again before the next state.
triggerWidthSamples=max(3,ceil(20e-6*rate-1e-9));
shortest=min(blanketSamples,targetSamples);
if shortest<=triggerWidthSamples
    error("adaptive_optopatch:BlanketStateTooShort", ...
        "The shortest blanket-mode state is %d samples (%.4g us), but the " + ...
        "DMD trigger pulse is %d samples and must fall before the next " + ...
        "state.",shortest,1e6*shortest/rate,triggerWidthSamples);
end
if guardSamples>=targetSamples
    error("adaptive_optopatch:BlanketGuardTooLong", ...
        "target_onset_guard_s covers the whole target state.");
end

timing=struct("rate",rate,"cycle",cycleSamples,"blanket",blanketSamples, ...
    "target",targetSamples,"guard",guardSamples,"frame",frameSamples, ...
    "blanket_v",blanket.mod488_v,"cycle_period_s",blanket.cycle_period_s);
switch blanket.schedule
    case "round_robin"
        program=round_robin_program(protocol,blanket,timing);
    case "recruitment_sweep"
        program=recruitment_sweep_program(protocol,blanket,timing);
    otherwise
        program=population_sweep_program(protocol,blanket,timing);
end

startSample=exact_samples(program.start_s,rate,"programmed unit start");
if mod(startSample,frameSamples)~=0
    error("adaptive_optopatch:BlanketRoundNotOnCameraFrame", ...
        "The programmed unit must start on a camera frame boundary.");
end
finalSample=startSample+program.repeats*program.samples;
totalSamples=round(rate*double(protocol.acquisition_duration_s));
if finalSample>totalSamples
    error("adaptive_optopatch:BlanketRoundsOutsideAcquisition", ...
        "%d repetition(s) of the programmed unit end at sample %d, after " + ...
        "the %d-sample acquisition.",program.repeats,finalSample,totalSamples);
end
states=program.states;
if sum(states.duration_samples)~=program.samples
    error("adaptive_optopatch:BlanketStateTableInconsistent", ...
        "Internal error: the states cover %d samples of a %d-sample unit.", ...
        sum(states.duration_samples),program.samples);
end

stateTable=struct("schema_version","1.1.0", ...
    "schedule",blanket.schedule, ...
    "sample_rate_hz",rate, ...
    "camera_frame_samples",frameSamples, ...
    "cycle_samples",cycleSamples, ...
    "blanket_samples",blanketSamples, ...
    "target_samples",targetSamples, ...
    "target_onset_guard_samples",guardSamples, ...
    "dmd_trigger_width_samples",triggerWidthSamples, ...
    "dmd_trigger_lead_samples",0, ...
    "blanket_mod488_v",blanket.mod488_v, ...
    "cell_ids",program.cell_ids, ...
    "epoch_cycles",program.epoch_cycles, ...
    "gap_cycles",program.gap_cycles, ...
    "round_start_sample",startSample, ...
    "round_samples",program.samples, ...
    "round_count",program.repeats, ...
    "states_per_round",height(states), ...
    "expected_trigger_count",height(states)*program.repeats, ...
    "final_sample",finalSample, ...
    "states",states);
end

% -----------------------------------------------------------------------
% One programmed unit per schedule. Each returns the same struct: the state
% table of the unit, its length in samples, where it starts, how many times
% the DAQ repeats it, and the cycle counts the archive reports.
% -----------------------------------------------------------------------

function program=round_robin_program(protocol,blanket,timing)
realized=blanket.round;
cellIds=realized.cell_ids; nCells=numel(cellIds);
epochCycles=round(realized.epoch_duration_s/timing.cycle_period_s);
gapCycles=round(realized.inter_epoch_gap_s/timing.cycle_period_s);
slotSamples=(epochCycles+gapCycles)*timing.cycle;
roundSamples=nCells*slotSamples;
startSample=exact_samples(realized.start_s,timing.rate,"round start");
roundEvents=validate_events_repeat_round(protocol.events,realized,timing.rate, ...
    startSample,roundSamples,slotSamples,epochCycles*timing.cycle);

builder=state_builder(timing);
for position=1:nCells
    event=roundEvents(position,:);
    targetKey="target:"+string(event.target_index)+"|"+ ...
        string(event.blue_mask_adjustment_pixels);
    context=struct("position",position,"segment_index",position, ...
        "level_v",double(event.command_voltage_v), ...
        "target_cell_id",string(event.target_cell_id), ...
        "target_index",double(event.target_index), ...
        "adjustment",double(event.blue_mask_adjustment_pixels), ...
        "pulse_id",double(event.pulse_id));
    builder=add_epoch(builder,epochCycles,targetKey, ...
        double(event.command_voltage_v),context);
    builder=add_gap(builder,gapCycles,context);
end
program=finish_program(builder,realized.start_s,realized.count, ...
    roundSamples,cellIds,epochCycles,gapCycles);
end

function program=recruitment_sweep_program(protocol,blanket,timing)
sweep=blanket.sweep;
segments=sweep.segments;
stepCycles=round(sweep.segment_duration_s/timing.cycle_period_s);
validate_sweep_events(protocol.events,segments,timing.rate, ...
    sweep.segment_duration_s,true);
builder=state_builder(timing);
for k=1:height(segments)
    context=struct("position",0,"segment_index",k, ...
        "level_v",double(segments.level_v(k)),"target_cell_id","", ...
        "target_index",0,"adjustment",NaN, ...
        "pulse_id",double(segments.pulse_id(k)));
    % Blanket at THIS STEP's level, then dark. No target phase at all: the
    % sweep exists to find where the blanket alone recruits cells.
    for cycle=1:stepCycles
        builder=add_state(builder,"blanket","step","blanket", ...
            timing.blanket,double(segments.level_v(k)),0,cycle,context);
        builder=add_state(builder,"dark","step","blank", ...
            timing.target,0,0,cycle,context);
    end
end
program=finish_program(builder,sweep.start_s,1, ...
    height(segments)*stepCycles*timing.cycle,strings(0,1),0,0);
end

function program=population_sweep_program(protocol,blanket,timing)
sweep=blanket.sweep;
segments=sweep.segments;
epochCycles=round(sweep.segment_duration_s/timing.cycle_period_s);
gapCycles=round(sweep.inter_segment_gap_s/timing.cycle_period_s);
validate_sweep_events(protocol.events,segments,timing.rate, ...
    sweep.segment_duration_s,false);
builder=state_builder(timing);
for k=1:height(segments)
    context=struct("position",0,"segment_index",k, ...
        "level_v",double(segments.level_v(k)),"target_cell_id","population", ...
        "target_index",0,"adjustment",sweep.blue_mask_adjustment_pixels, ...
        "pulse_id",double(segments.pulse_id(k)));
    builder=add_epoch(builder,epochCycles,"population", ...
        double(segments.level_v(k)),context);
    builder=add_gap(builder,gapCycles,context);
end
program=finish_program(builder,sweep.start_s,1, ...
    height(segments)*(epochCycles+gapCycles)*timing.cycle, ...
    sweep.population_cell_ids,epochCycles,gapCycles);
end

% -----------------------------------------------------------------------
% The one place a cycle becomes two states.
% -----------------------------------------------------------------------

function builder=add_epoch(builder,cycles,targetKey,targetVoltage,context)
for cycle=1:cycles
    builder=add_state(builder,"blanket","epoch","blanket", ...
        builder.timing.blanket,builder.timing.blanket_v,0,cycle,context);
    builder=add_state(builder,"target","epoch",targetKey, ...
        builder.timing.target,targetVoltage,builder.timing.guard,cycle,context);
end
end

function builder=add_gap(builder,cycles,context)
context.target_cell_id=""; context.target_index=0;
for cycle=1:cycles
    builder=add_state(builder,"blanket","gap","blanket", ...
        builder.timing.blanket,builder.timing.blanket_v,0,cycle,context);
    builder=add_state(builder,"dark","gap","blank", ...
        builder.timing.target,0,0,cycle,context);
end
end

function builder=state_builder(timing)
builder=struct("timing",timing,"sample",0,"rows",{cell(0,1)});
end

function builder=add_state(builder,type,segment,key,samples,voltage,guard,cycle,context)
builder.rows{end+1,1}=struct( ...
    "state_type",string(type),"segment",string(segment), ...
    "segment_index",double(context.segment_index), ...
    "position_in_round",double(context.position), ...
    "cycle_in_segment",double(cycle), ...
    "start_sample",builder.sample,"duration_samples",double(samples), ...
    "mod488_v",double(voltage),"mod488_guard_samples",double(guard), ...
    "mask_key",string(key),"level_v",double(context.level_v), ...
    "target_cell_id",string(context.target_cell_id), ...
    "target_index",double(context.target_index), ...
    "blue_mask_adjustment_pixels",double(context.adjustment), ...
    "logical_pulse_id",double(context.pulse_id));
builder.sample=builder.sample+samples;
end

function program=finish_program(builder,startS,repeats,samples,cellIds, ...
        epochCycles,gapCycles)
rows=vertcat(builder.rows{:});
states=struct2table(rows);
states=addvars(states,(1:height(states))',Before=1,NewVariableNames="state_index");
program=struct("states",states,"samples",samples,"start_s",startS, ...
    "repeats",repeats,"cell_ids",reshape(string(cellIds),[],1), ...
    "epoch_cycles",epochCycles,"gap_cycles",gapCycles);
end

% -----------------------------------------------------------------------
% The logical events must be exactly what the frozen schedule will deliver.
% -----------------------------------------------------------------------

function validate_sweep_events(events,segments,rate,segmentDurationS,expectNull)
[~,order]=sort(events.onset_s); events=events(order,:);
if height(events)~=height(segments)
    error("adaptive_optopatch:BlanketSweepEventsMismatch", ...
        "The acquisition has %d logical segments but its frozen sweep has %d.", ...
        height(events),height(segments));
end
if any(events.is_null~=expectNull)
    error("adaptive_optopatch:BlanketSweepEventsMismatch", ...
        "Every blanket recruitment-sweep segment must be a null event, and " + ...
        "every population-target epoch a non-null 1P DMD event.");
end
bad=find(abs(events.onset_s*rate-double(segments.onset_s)*rate)>1e-6 | ...
    abs(events.duration_s-segmentDurationS)>1e-12 | ...
    double(events.pulse_id)~=double(segments.pulse_id),1);
if ~isempty(bad)
    error("adaptive_optopatch:BlanketSweepEventsMismatch", ...
        "Logical segment %d (pulse %s at %.6g s for %.6g s) is not where " + ...
        "the frozen sweep puts it (pulse %d at %.6g s for %.6g s).", ...
        bad,string(events.pulse_id(bad)),events.onset_s(bad), ...
        events.duration_s(bad),segments.pulse_id(bad), ...
        segments.onset_s(bad),segmentDurationS);
end
if ~expectNull && any(abs(events.command_voltage_v- ...
        double(segments.level_v))>1e-12)
    error("adaptive_optopatch:BlanketSweepEventsMismatch", ...
        "A population-target epoch commands a voltage its frozen sweep " + ...
        "level does not.");
end
end

function roundEvents=validate_events_repeat_round(events,realized,rate, ...
        roundStartSample,roundSamples,slotSamples,epochSamples)
% The resolved events must be exactly what the wrapped round will deliver.
[~,order]=sort(events.onset_s); events=events(order,:);
nCells=numel(realized.cell_ids);
expectedCount=nCells*realized.count;
if height(events)~=expectedCount
    error("adaptive_optopatch:BlanketEventsNotWholeRounds", ...
        "The acquisition has %d target epochs; %d complete rounds of %d " + ...
        "cells need exactly %d.",height(events),realized.count,nCells,expectedCount);
end
if any(events.is_null) || any(events.stimulation_source~="1p_dmd")
    error("adaptive_optopatch:BlanketEventsNotWholeRounds", ...
        "Every blanket-mode event must be a non-null 1P DMD target epoch.");
end
k=(0:expectedCount-1)';
roundIndex=floor(k/nCells); position=mod(k,nCells)+1;
expectedOnset=roundStartSample+roundIndex*roundSamples+(position-1)*slotSamples;
onset=round(events.onset_s*rate);
duration=round(events.duration_s*rate);
bad=find(abs(events.onset_s*rate-expectedOnset)>1e-6 | ...
    abs(events.duration_s*rate-epochSamples)>1e-6 | ...
    events.target_cell_id~=realized.cell_ids(position),1);
if ~isempty(bad)
    error("adaptive_optopatch:BlanketEventsNotWholeRounds", ...
        "Epoch %s (%s at sample %d, %d samples) is not where the frozen " + ...
        "round puts position %d of round %d (%s at sample %d, %d samples).", ...
        string(events.pulse_id(bad)),events.target_cell_id(bad),onset(bad), ...
        duration(bad),position(bad),roundIndex(bad)+1, ...
        realized.cell_ids(position(bad)),expectedOnset(bad),epochSamples);
end
roundEvents=events(1:nCells,:);
for p=1:nCells
    same=events(position==p,:);
    if any(same.command_voltage_v~=roundEvents.command_voltage_v(p)) || ...
            any(same.target_index~=roundEvents.target_index(p)) || ...
            any(same.blue_mask_adjustment_pixels~=roundEvents.blue_mask_adjustment_pixels(p))
        error("adaptive_optopatch:BlanketEventsNotWholeRounds", ...
            "%s does not have the same voltage, target and mask in every " + ...
            "round, but the DMD and mod488 replay round 1 for all of them.", ...
            realized.cell_ids(p));
    end
end
end

function samples=exact_samples(seconds,rate,label)
samples=double(seconds)*rate;
if ~isfinite(samples) || abs(samples-round(samples))>1e-6
    error("adaptive_optopatch:BlanketTimingNotWholeSamples", ...
        "%s is %.9g s, which is %.6g samples at %.0f Hz. Blanket timing " + ...
        "must be a whole number of DAQ samples.",label,seconds,samples,rate);
end
samples=round(samples);
end
