function protocol=generate_blanket_round_robin_protocol(options)
%GENERATE_BLANKET_ROUND_ROBIN_PROTOCOL Fixed-order round robin with blanket depolarization.
%
%   protocol=GENERATE_BLANKET_ROUND_ROBIN_PROTOCOL(...) returns a
%   field-of-view-independent schema-4 definition for inhibitory-cell round
%   robins: every cycle every Stim-enabled cell gets a short blanket pulse, and
%   the target of the current epoch gets the rest of the cycle at its own
%   calibrated Blue voltage. See BLANKET_DEPOLARIZATION_SPEC for the optics.
%
%   Each acquisition is `Rounds` complete rounds of
%
%       cell 1 epoch, gap, cell 2 epoch, gap, ..., cell N epoch, gap
%
%   over the cells Stim-enabled at Update plan, in FOV order. The order is
%   fixed because the DMD stores one round and wraps it.
%
%   BlanketMod488V has no default. It is an explicit experimental choice and
%   the definition is refused without it.
%
%   See also BLANKET_DEPOLARIZATION_SPEC, RESOLVE_PROTOCOL.
arguments
    options.BlanketMod488V (1,1) double = NaN
    options.Rounds (1,1) double {mustBePositive,mustBeInteger} = 100
    options.EpochDurationS (1,1) double {mustBePositive} = 0.020
    options.InterEpochGapS (1,1) double {mustBePositive} = 0.010
    options.CyclePeriodS (1,1) double {mustBePositive} = 0.001
    options.BlanketFraction (1,1) double = 0.20
    options.TargetOnsetGuardS (1,1) double {mustBeNonnegative} = 50e-6
    options.PreDelayS (1,1) double {mustBeNonnegative} = 0.100
    options.PostDelayS (1,1) double {mustBeNonnegative} = 0.100
    options.AcquisitionCount (1,1) double {mustBePositive,mustBeInteger} = 1
    options.CommandVoltageV (1,1) double = NaN
    options.ProtocolId (1,1) string = "blanket_round_robin"
end
if isfinite(options.CommandVoltageV) && ...
        (options.CommandVoltageV<=0 || options.CommandVoltageV>5)
    error("adaptive_optopatch:InvalidRoundRobinVoltage", ...
        "CommandVoltageV must be NaN, which defers to each cell's own Blue " + ...
        "calibration, or an explicit override in (0,5] V.");
end
acquisitionCells=cell(options.AcquisitionCount,1);
for index=1:options.AcquisitionCount
    conditionId=sprintf("blanket_round_robin_%02d",index);
    scheduler=struct("type","blanket_round_robin", ...
        "rounds",options.Rounds, ...
        "epoch_duration_s",options.EpochDurationS, ...
        "inter_epoch_gap_s",options.InterEpochGapS, ...
        "pre_delay_s",options.PreDelayS, ...
        "chunk_index",index, ...
        "chunk_count",options.AcquisitionCount);
    acquisitionCells{index}=struct( ...
        "acquisition_id",string(conditionId), ...
        "events",template_event(conditionId,options), ...
        "parameters",struct, ...
        "event_order_realized",true, ...
        "target_repetitions",1, ...
        "post_delay_s",options.PostDelayS, ...
        "scheduler",scheduler);
end
blanket=struct("enabled",true, ...
    "mod488_v",options.BlanketMod488V, ...
    "cycle_period_s",options.CyclePeriodS, ...
    "blanket_fraction",options.BlanketFraction, ...
    "target_onset_guard_s",options.TargetOnsetGuardS);
sources=struct("command_voltage_v",["event","acquisition","protocol","fov_cell"]);
protocol=struct("schema_version","4.0.0", ...
    "artifact_type","experiment_definition", ...
    "protocol_id",options.ProtocolId, ...
    "protocol_type","blanket_round_robin", ...
    "created_at",string(datetime("now","TimeZone","local")), ...
    "target_policy","multi_target_continuous", ...
    "event_order","ordered","random_seed",0, ...
    "parameter_sources",sources,"parameters",struct, ...
    "blanket_depolarization",blanket, ...
    "acquisitions",vertcat(acquisitionCells{:}));
protocol=adaptive_optopatch.normalize_protocol(protocol);
end

function events=template_event(conditionId,options)
% The event tier of parameter resolution, not a pulse; see
% generate_connectivity_chunked_protocol.
pulse_id=1;
condition_id=string(conditionId);
stimulation_source="1p_dmd";
onset_s=NaN;
duration_s=options.EpochDurationS;
is_null=false;
command_voltage_v=options.CommandVoltageV;
blue_mask_adjustment_pixels=NaN;
events=table(pulse_id,condition_id,stimulation_source,onset_s,duration_s, ...
    is_null,command_voltage_v,blue_mask_adjustment_pixels);
end
