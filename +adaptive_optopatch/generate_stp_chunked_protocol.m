function protocol=generate_stp_chunked_protocol(options)
%GENERATE_STP_CHUNKED_PROTOCOL Reusable 20 Hz trains for Stim-enabled cells.
% Targets and literal event timing are resolved and frozen at Update plan.
arguments
    options.TotalTrainsPerCell (1,1) double {mustBePositive,mustBeInteger} = 300
    options.TrainsPerCellPerChunk (1,1) double {mustBePositive,mustBeInteger} = 50
    options.PulsesPerTrain (1,1) double {mustBePositive,mustBeInteger} = 5
    options.FrequencyHz (1,1) double {mustBePositive} = 20
    options.PulseDurationS (1,1) double {mustBePositive} = 0.010
    options.PreferredInterTrainGapS (1,1) double {mustBeNonnegative} = 0.020
    options.MinimumSameCellPostTrainGapS (1,1) double {mustBeNonnegative} = 1.000
    options.PreDelayS (1,1) double {mustBeNonnegative} = 0.100
    options.PostDelayS (1,1) double {mustBeNonnegative} = 0.100
    options.BaseRandomSeed (1,1) double {mustBeNonnegative,mustBeInteger} = 3001
    options.CommandVoltageV (1,1) double = NaN
    options.FlutMaxEntries (1,1) double {mustBePositive,mustBeInteger} = 4096
end
if mod(options.TotalTrainsPerCell,options.TrainsPerCellPerChunk)~=0
    error("adaptive_optopatch:StpChunkSizeNotDivisible", ...
        "TotalTrainsPerCell must be divisible by TrainsPerCellPerChunk.");
end
if options.PulsesPerTrain>1 && ...
        options.PulseDurationS>=1/options.FrequencyHz-1e-12
    error("adaptive_optopatch:OverlappingStpPulses", ...
        "Pulse duration must be shorter than the pulse period.");
end
if isfinite(options.CommandVoltageV) && ...
        (options.CommandVoltageV<=0 || options.CommandVoltageV>5)
    error("adaptive_optopatch:InvalidStpVoltage", ...
        "CommandVoltageV must be NaN or an explicit voltage in (0,5] V.");
end
chunkCount=options.TotalTrainsPerCell/options.TrainsPerCellPerChunk;
acquisitions=cell(chunkCount,1);
for chunkIndex=1:chunkCount
    conditionId=sprintf("stp_%ghz_%dpulse_chunk_%02d", ...
        options.FrequencyHz,options.PulsesPerTrain,chunkIndex);
    scheduler=struct("type","constrained_stp_round_robin", ...
        "trains_per_cell",options.TrainsPerCellPerChunk, ...
        "pulses_per_train",options.PulsesPerTrain, ...
        "frequency_hz",options.FrequencyHz, ...
        "pulse_duration_s",options.PulseDurationS, ...
        "preferred_inter_train_gap_s",options.PreferredInterTrainGapS, ...
        "minimum_same_cell_post_train_gap_s", ...
            options.MinimumSameCellPostTrainGapS, ...
        "pre_delay_s",options.PreDelayS, ...
        "random_seed",options.BaseRandomSeed+chunkIndex-1, ...
        "flut_max_entries",options.FlutMaxEntries, ...
        "chunk_index",chunkIndex,"chunk_count",chunkCount);
    events=table(1,string(conditionId),"1p_dmd",NaN, ...
        options.PulseDurationS,false,options.CommandVoltageV,NaN, ...
        'VariableNames',{'pulse_id','condition_id','stimulation_source', ...
        'onset_s','duration_s','is_null','command_voltage_v', ...
        'blue_mask_adjustment_pixels'});
    acquisitions{chunkIndex}=struct("acquisition_id",string(conditionId), ...
        "events",events,"parameters",struct,"event_order_realized",true, ...
        "target_repetitions",1,"post_delay_s",options.PostDelayS, ...
        "scheduler",scheduler);
end
protocol=struct("schema_version","4.0.0", ...
    "artifact_type","experiment_definition", ...
    "protocol_id","stp_screen_stim_enabled_"+options.BaseRandomSeed, ...
    "protocol_type","stp_screen", ...
    "created_at",string(datetime("now","TimeZone","local")), ...
    "target_policy","multi_target_continuous", ...
    "event_order","randomized","random_seed",options.BaseRandomSeed, ...
    "parameter_sources",struct("command_voltage_v", ...
        ["event","acquisition","protocol","fov_cell"]), ...
    "parameters",struct,"acquisitions",vertcat(acquisitions{:}));
protocol=adaptive_optopatch.normalize_protocol(protocol);
end
