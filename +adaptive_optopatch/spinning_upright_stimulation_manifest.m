function manifest=spinning_upright_stimulation_manifest()
%SPINNING_UPRIGHT_STIMULATION_MANIFEST Physical outputs for 1P AO runs.
% The rig initializer supplies terminals; the 2026-10-13 archive confirms
% mod488 pulse commands and shutter488 open commands during stimulation.
profile=adaptive_optopatch.spinning_upright_1p_profile();
manifest=struct;
manifest.schema_version="1.0.0";
manifest.rig_name=profile.rig_name;
manifest.source=profile.source;
manifest.script_owner=adaptive_optopatch.script_owner_tag();
manifest.alias_list={ ...
    "Dev1/ao0","mod488";"Dev1/ao1","mod607"; ...
    "Dev1/ao2","PatchCmd";"Dev1/ao3","780 LED"; ...
    "Dev1/port0/line0","shutter488"; ...
    "Dev1/port0/line1","shutter607"; ...
    "Dev1/port0/line2","Shutter sensory"; ...
    "Dev1/port0/line4","DMD Trigger"; ...
    "Dev1/port0/line9","IR Trigger"};
manifest.outputs=[ ...
    entry("blue_modulator","mod488","Dev1/ao0","mod488","ao", ...
        "ao_owned_stimulation",true,0,"spinning_upright_1p_profile.modulator.dark_v", ...
        "buffered","488 nm pulse command; 0 V is the declared dark setting."); ...
    entry("blue_shutter","shutter488","Dev1/port0/line0","shutter488","do", ...
        "ao_owned_stimulation",true,0,"spinning_upright_1p_profile.shutter.closed_state", ...
        "imperative","488 nm shutter; AO closes it before and after each run."); ...
    entry("blue_dmd_advance_trigger","DMD Trigger","Dev1/port0/line4", ...
        "DMD Trigger","do","ao_owned_stimulation",true,0, ...
        "spinning_upright_1p_profile.dmd.trigger_safe_state", ...
        "buffered","Blue DMD pattern advance trigger; low is the idle state.")];
% The Virtual Upright took ownership of its 594 nm recording illumination
% when it stopped inheriting the operator's Waveforms protocol. This rig has
% not: its camera is counter-triggered through a different path, its profile
% declares no camera cadence and no orange modulator, and nothing has been
% checked on it. So mod607 and shutter607 stay the operator's, and this list
% stays empty rather than being filled in by analogy.
manifest.recording_illumination=manifest_outputs_empty();
manifest.inherited=[ ...
    entry("orange_modulator","mod607","Dev1/ao1","mod607","ao", ...
        "inherited_non_stimulation",false,[],"","operator", ...
        "607 nm recording illumination from the active Luminos protocol."); ...
    entry("orange_shutter","shutter607","Dev1/port0/line1","shutter607","do", ...
        "inherited_non_stimulation",false,[],"","operator", ...
        "607 nm recording shutter from the active Luminos protocol.")];
manifest.luminos_infrastructure=entry("camera_trigger", ...
    "Orca Flash Orange","Dev1/Ctr0",strings(1,0),"ctro", ...
    "expected_luminos_infrastructure",false,[],"","luminos", ...
    "Voltage camera trigger generated by Luminos.");
manifest.unresolved=[ ...
    entry("patch_command","PatchCmd","Dev1/ao2","PatchCmd","ao", ...
        "unresolved",missing,[],"","unknown", ...
        "Electrophysiology command; AO has not classified its active waveform."); ...
    entry("infrared_led","780 LED","Dev1/ao3","780 LED","ao", ...
        "unresolved",missing,[],"","unknown", ...
        "780 nm LED; AO does not command or classify it."); ...
    entry("sensory_shutter","Shutter sensory","Dev1/port0/line2", ...
        "Shutter sensory","do","unresolved",missing,[],"","unknown", ...
        "Sensory stimulation shutter; AO must not infer its safe state."); ...
    entry("infrared_trigger","IR Trigger","Dev1/port0/line9", ...
        "IR Trigger","do","unresolved",missing,[],"","unknown", ...
        "IR trigger; AO has not classified its active waveform.")];
end

function records=manifest_outputs_empty()
%MANIFEST_OUTPUTS_EMPTY An empty declaration list with the right fields.
records=entry("","","",strings(1,0),"","unresolved",missing,[],"","unknown","");
records(:)=[];
end

function record=entry(role,name,terminal,aliases,kind,classification, ...
        stimulation,neutral,source,runtimeOwner,reason)
record=struct("role",string(role),"device_name",string(name), ...
    "terminal",string(terminal), ...
    "aliases",reshape(string(aliases),1,[]),"kind",string(kind), ...
    "reason",string(reason),"classification",string(classification), ...
    "stimulation_capable",stimulation,"neutral_value",neutral, ...
    "neutral_source",string(source), ...
    "owner",struct("one_photon",string(runtimeOwner), ...
        "two_photon","unsupported","mixed","unsupported"));
end
