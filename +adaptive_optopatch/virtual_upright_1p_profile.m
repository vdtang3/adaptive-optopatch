function profile = virtual_upright_1p_profile()
%VIRTUAL_UPRIGHT_1P_PROFILE Declared Luminos hardware for blue-DMD stimulation.
% Physical wiring and live device properties are checked again before output.

profile = struct;
profile.schema_version = "0.2.0";
profile.profile_id = "virtual_upright_488_dmd_blue";
profile.rig_name = "Virtual_Upright";
profile.source = "src/Applications/Virtual_Upright/Virtual_Upright.json";
% TIMING AUTHORITY, not a description of what somebody selected. Adaptive
% Optopatch builds DAQ.global_props from these values at the start of every
% acquisition instead of inheriting whatever the Waveforms tab was left on,
% so this struct is what decides the sample clock the experiment runs at.
%
% default_clock is "Internal Dev1" and NOT the "Dev1/PFI0" the rig file
% offers as its default. Dev1/PFI0 is the Orca Fusion's own line clock, and
% an AO acquisition triggers that camera from the DAQ - so clocking the DAQ
% from the camera it is triggering is circular. Both run at 200 kHz, which
% is why nothing has visibly broken; DESIGN.md used to describe the
% Spinning Upright's camera-clocked arrangement as if it were this rig's.
profile.daq = struct("name","Dev1", ...
    "default_clock","Internal Dev1", ...
    "sample_rate_hz",200000, ...
    "supported_internal_masters",["Dev1","Dev2"], ...
    "synchronization_branch","VU_MultiDAQ_Synchronization", ...
    "requires_self_trigger",true);
profile.daq.default_trigger=["Dev1/PFI9","Dev2/PFI1"];
profile.daq.clock_bridge=["Dev1/PFI12","Dev2/PFI0"];
% frame_trigger_source, frame_period_ms and acquisition_exposure_s are the
% cadence AO imposes on the voltage camera for the length of an
% acquisition, captured and restored around it. A rig profile that omits
% them keeps the older behaviour of inheriting the Camera tab's cadence.
%
% frame_trigger_source "DAQ" is the whole synchronous-readout switch:
% Camera.set.frametrigger_source calls Set_Readout_Mode(1), which is
% Hamamatsu external synchronous-triggered mode - one frame per trigger,
% each frame ending when the next trigger arrives. Trigger polarity,
% overlap, readout speed and acquisition mode have no MATLAB-side property
% to set and are not needed for this cadence.
%
% acquisition_exposure_s equals the frame period because in that mode
% Camera.calculate_framerate reads the exposure AS the period between
% triggers. ROI, binning and FOV are deliberately absent: they stay the
% Camera tab's.
profile.camera = struct("name","Orca Fusion", ...
    "serial","001125", ...
    "clock","Dev1/PFI0", ...
    "hsync_rate_hz",200000, ...
    "trigger","Dev1/port0/line3", ...
    "frame_trigger_source","DAQ", ...
    "frame_period_ms",1.0, ...
    "acquisition_exposure_s",0.001);
profile.dmd = struct("name","DMD_Blue", ...
    "device_type","ALP_DMD", ...
    "trigger_port","Dev1/port0/line4", ...
    "trigger_alias","DMD Trigger");
profile.orange_dmd=struct("name","DMD_Orange","device_type","ALP_DMD");
profile.laser = struct("name","488", ...
    "device_type","OBIS_Laser", ...
    "com_port","COM9", ...
    "wavelength_nm",488, ...
    "max_power_w",0.055);
profile.modulator = struct("name","mod488", ...
    "device_type","NI_DAQ_Modulator", ...
    "port","Dev1/ao2", ...
    "minimum_v",0, ...
    "maximum_v",5, ...
    "dark_v",0);
% Outputs owned by the inactive 2P modality. These values are explicit rig
% safety declarations so waveform builders never infer that zero is safe.
profile.inactive_two_photon = struct( ...
    "scanner",struct("name","Chameleon (To friends: Ben)", ...
        "x_name","Adaptive2P_X","x_port","Dev2/ao0", ...
        "y_name","Adaptive2P_Y","y_port","Dev2/ao1", ...
        "stationary_v",[0 0]), ...
    "modulator",struct("name","2P mod","port","Dev1/ao3", ...
        "dark_v",0), ...
    "safe_value_source","virtual_upright_1p_profile rig safety declaration");
profile.shutter = struct("name","shutter488", ...
    "device_type","NI_DAQ_Shutter", ...
    "port","Dev1/port0/line0", ...
    "closed_state",false, ...
    "open_state",true);
% ORANGE RECORDING ILLUMINATION, which AO owns for the length of an
% acquisition and nothing else. 594 nm does not stimulate the preparation;
% it is what the voltage indicator is read out with, and without it the
% recording is dark. It used to arrive as whatever record the operator's
% Waveforms protocol happened to carry on Dev1/ao1, which is the second
% reason AO needed a protocol loaded at all.
%
% recording_v has NO DEFAULT. Zero would record a black movie and a guess
% would silently change everybody's photobleaching; the operator chooses it
% against the live view with the recording mask projected, and the plan
% refuses to become runnable until they have. See the Orange recording
% voltage control, and README's "Choosing the orange recording voltage".
profile.orange_modulator = struct("name","mod594", ...
    "device_type","NI_DAQ_Modulator", ...
    "port","Dev1/ao1", ...
    "minimum_v",0, ...
    "maximum_v",5, ...
    "dark_v",0, ...
    "recording_v",NaN);
% Driven imperatively, exactly as shutter488 is and for the same reason: an
% NI_DAQ_Shutter is an on-demand digital write, so a buffered record and
% the runner's own open/close would be two runtime owners of one line.
profile.orange_shutter = struct("name","shutter594", ...
    "device_type","NI_DAQ_Shutter", ...
    "port","Dev1/port0/line1", ...
    "closed_state",false, ...
    "open_state",true);
end
