classdef TestSpinningUprightPort < matlab.unittest.TestCase
    methods (Test)
        function selectsOrangeVoltageCameraWithoutObis(testCase)
            app=adaptive_optopatch.testing.make_simulated_luminos( ...
                "RigName","Spinning_Upright");
            profile=adaptive_optopatch.one_photon_profile_for_rig(app);
            hardware=adaptive_optopatch.resolve_luminos_1p_hardware(app,profile);
            testCase.verifyEqual(profile.modulator.port,"Dev1/ao0");
            testCase.verifyEqual(hardware.voltage_camera.cam_id,"S/N: 002312");
            testCase.verifyEqual(hardware.voltage_camera_index,1);
            testCase.verifyEmpty(hardware.laser);
            testCase.verifyTrue(hardware.daq_sync.passed);
        end

        function preservesUnownedSpinningUprightOutputs(testCase)
            profile=adaptive_optopatch.spinning_upright_1p_profile();
            manifest=adaptive_optopatch.spinning_upright_stimulation_manifest();
            protocol=resolved_protocol();
            ambient=struct("ao",[constant("old blue","mod488",3), ...
                constant("recording","mod607",2), ...
                constant("patch","PatchCmd",1), ...
                constant("infrared","780 LED",2)], ...
                "do",[],"ai",[],"di",[],"ctri",[], ...
                "ao_camera_triggered",[],"do_camera_triggered",[]);
            props=struct("rate",200000,"total_time",1, ...
                "clock_source","Dev1/PFI0","trigger_source","Dev1/PFI12", ...
                "completion_trigger","None","daq_master",true);
            [globalProps,configured]= ...
                adaptive_optopatch.build_luminos_mixed_waveform_config( ...
                props,ambient,protocol,"OnePhotonProfile",profile, ...
                "Manifest",manifest);
            ports=string({configured.ao.port});
            testCase.verifyEqual(sum(ports=="mod488"),1);
            testCase.verifyTrue(any(ports=="mod607"));
            testCase.verifyTrue(any(ports=="PatchCmd"));
            testCase.verifyTrue(any(ports=="780 LED"));
            testCase.verifyEqual(numel(configured.ai),1);
            testCase.verifyEqual(string(configured.ai(1).port),"Dev1/ai12");
            testCase.verifyEqual(string(configured.ai(1).name), ...
                "AO_AI12_monitor_unverified");
            report=adaptive_optopatch.account_stimulation_outputs( ...
                globalProps,configured,"Manifest",manifest,"Modality","1p_dmd", ...
                "Policy","report_only");
            testCase.verifyTrue(report.passed);
        end

        function reusesExistingAi12Input(testCase)
            profile=adaptive_optopatch.spinning_upright_1p_profile();
            records=struct("name","Operator AI12","port","/Dev1/ai12", ...
                "id",123);
            [configured,report]=adaptive_optopatch.ensure_auxiliary_input( ...
                records,profile);
            testCase.verifyEqual(numel(configured),1);
            testCase.verifyEqual(configured,records);
            testCase.verifyEqual(report.source,"operator_waveform");
            testCase.verifyEqual(report.identity,"unverified");
        end

        function namesExistingUnnamedAi12Input(testCase)
            profile=adaptive_optopatch.spinning_upright_1p_profile();
            records=struct("name","","port","Dev1/ai12","id",123);
            [configured,report]=adaptive_optopatch.ensure_auxiliary_input( ...
                records,profile);
            testCase.verifyEqual(numel(configured),1);
            testCase.verifyEqual(string(configured.name), ...
                "AO_AI12_monitor_unverified");
            testCase.verifyEqual(report.source,"operator_waveform_unnamed");
        end

        function doesNotLookUpAbsentTwoPhotonHardware(testCase)
            app=adaptive_optopatch.testing.make_simulated_luminos( ...
                "RigName","Spinning_Upright");
            profile=adaptive_optopatch.spinning_upright_1p_profile();
            report=adaptive_optopatch.neutralize_all_stimulation(app, ...
                "Manifest",adaptive_optopatch.spinning_upright_stimulation_manifest(), ...
                "OnePhotonProfile",profile,"Modality","1p_dmd");
            testCase.verifyTrue(report.all_succeeded);
            testCase.verifyFalse(any(contains(app.DeviceLookupLog,"2P mod")));
            testCase.verifyFalse(any(contains(app.DeviceLookupLog,"Chameleon")));
        end

        function rejectsSavedVirtualUprightFov(testCase)
            app=adaptive_optopatch.testing.make_simulated_luminos( ...
                "RigName","Spinning_Upright");
            controller=adaptive_optopatch.AdaptiveOptopatchController( ...
                "LuminosApp",app);
            [fovState,~]=AoFixtures.fovState();
            testCase.verifyError(@()controller.setFovState(fovState), ...
                "adaptive_optopatch:WrongReferenceCamera");
        end

        function runsOnePhotonAcquisitionOnSimulatedRig(testCase)
            outputRoot=string(tempname);
            testCase.addTeardown(@()AoFixtures.removeFolder(outputRoot));
            app=adaptive_optopatch.testing.make_simulated_luminos( ...
                "RigName","Spinning_Upright", ...
                "SimulationOutputRoot",outputRoot,"CameraRoi",[0 9 0 8]);
            protocol=resolved_protocol();
            target=struct("cell_id","cell_001","qc_pass",true, ...
                "stimulation_enabled",true,"recording_enabled",true);
            camera=AoFixtures.frameCameraGeometry([8 9]);
            camera.name="Orca Flash Orange";
            targets=struct("targets",target,"dmd_camera_masks",true(8,9,1), ...
                "canonical_roi_masks",true(8,9,1), ...
                "blank_dmd_mask",false(8,9), ...
                "reference_camera",camera, ...
                "parameters",struct("blue_mask_adjustment_pixels",0));
            trials=table(1,"1p_dmd","cell_001",false,1,{protocol}, ...
                protocol.acquisition_duration_s,"su_1p","planned","", ...
                'VariableNames',{'trial_id','stimulation_mode','target_cell_id', ...
                'is_null','target_index','pulse_schedule','acquisition_duration_s', ...
                'output_tag','acquisition_status','experiment_directory'});
            run=adaptive_optopatch.run_mixed_manifest( ...
                struct("trials",trials),targets,app, ...
                "ConfirmLiveOutput",true);
            testCase.verifyEqual(run.trials.acquisition_status,"completed");
            testCase.verifyEqual(run.hardware_profile.rig_name,"Spinning_Upright");
            executed=run.trials.executed_pulse_schedule{1};
            testCase.verifyEqual(executed.startup_baseline_s,2);
            testCase.verifyEqual(executed.events.onset_s(1), ...
                protocol.events.onset_s(1)+2);
            testCase.verifyEqual(executed.acquisition_duration_s, ...
                protocol.acquisition_duration_s+2);
            framePlan=run.trials.waveform_summary{1}.camera_frame_plan;
            testCase.verifyEqual(framePlan(2).calculation_method, ...
                "preserved_operator_setting");
            testCase.verifyEqual(framePlan(2).frames_requested,1);
            saved=load(fullfile(run.trials.experiment_directory, ...
                "output_data.mat"),"adaptive_optopatch_record");
            testCase.verifyTrue(isnan(saved.adaptive_optopatch_record.obis_power_w));
            testCase.verifyEqual(saved.adaptive_optopatch_record.pulse_schedule.events.onset_s(1), ...
                executed.events.onset_s(1));
        end
    end
end

function protocol=resolved_protocol()
definition=adaptive_optopatch.generate_screen_protocol( ...
    "PulseCount",1,"PulseDurationMs",5,"PreDelayMs",100, ...
    "PostDelayMs",100,"ModulatorVoltage",1);
protocol=AoFixtures.resolvedProtocol(definition,"1p_dmd");
end

function record=constant(name,port,value)
record=struct("name",char(name),"port",char(port), ...
    "wavefile","awfm_constant","params",{{double(value)}}, ...
    "operation","Multiplication","concatTime",[],"script_owner",[]);
end
